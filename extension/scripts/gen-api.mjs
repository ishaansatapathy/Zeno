// Generates what the extension knows about the API from the committed OpenAPI document
// (docs/openapi.json, itself checked against the real API by the Rust tests).
//
//   npm run api:types     rewrite src/shared/api-schema.d.ts
//   npm run api:check     fail if it is out of date (CI runs this)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = path.dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(fs.readFileSync(path.join(root, "../../docs/openapi.json"), "utf8"));
const out = path.join(root, "../src/shared/api-schema.d.ts");
const header = "// Generated by scripts/gen-api.mjs from docs/openapi.json: types for every route.\n// Do not edit by hand; run `npm run api:types`.\n\n";
const types = header + astToString(await openapiTS(spec, { alphabetize: true }));

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== types.replace(/\r\n/g, "\n")) {
    console.error("src/shared/api-schema.d.ts is out of date. Run `npm run api:types`.");
    process.exit(1);
  }
  console.log("api-schema.d.ts is up to date");
} else {
  fs.writeFileSync(out, types);
  console.log("wrote src/shared/api-schema.d.ts");
}
