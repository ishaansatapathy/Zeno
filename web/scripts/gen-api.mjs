// Generates what the web app knows about the API from the committed OpenAPI document
// (docs/openapi.json, itself checked against the real API by the Rust tests):
//
//   lib/api/schema.d.ts   every path, request body and response, as types
//   lib/api/limits.ts     the few numbers a form shows before the server answers
//
//   npm run api:types     rewrite both files
//   npm run api:check     fail if either is out of date (CI runs this)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = path.dirname(fileURLToPath(import.meta.url));
const specFile = path.join(root, "../../docs/openapi.json");
const outDir = path.join(root, "../lib/api");
const check = process.argv.includes("--check");

const header = (what) => `// Generated by scripts/gen-api.mjs from docs/openapi.json: ${what}\n// Do not edit by hand; run \`npm run api:types\`.\n\n`;

const spec = JSON.parse(fs.readFileSync(specFile, "utf8"));
const schemas = spec.components.schemas;

/** A number the document must state, or the build stops: a form must not guess at a limit. */
function limit(schema, field, key) {
  const value = schemas[schema]?.properties?.[field]?.[key];
  if (!Number.isInteger(value)) throw new Error(`docs/openapi.json does not state ${schema}.${field}.${key}`);
  return value;
}

const types = header("types for every route") + astToString(await openapiTS(spec, { alphabetize: true }));

const limits =
  header("limits the API enforces, for forms") +
  `export const limits = {
  passwordMin: ${limit("RegisterRequest", "password", "minLength")},
  passwordMax: ${limit("RegisterRequest", "password", "maxLength")},
  nameMin: ${limit("RegisterRequest", "name", "minLength")},
  nameMax: ${limit("RegisterRequest", "name", "maxLength")},
} as const;
`;

const outputs = [
  ["schema.d.ts", types],
  ["limits.ts", limits],
];

let stale = false;
for (const [name, content] of outputs) {
  const file = path.join(outDir, name);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
  if (check) {
    if (current !== content) {
      console.error(`web/lib/api/${name} is out of date. Run \`npm run api:types\` and commit the result.`);
      stale = true;
    }
  } else {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(file, content);
  }
}
if (stale) process.exit(1);
