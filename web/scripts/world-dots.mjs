// Builds lib/site/world-dots.ts: the world's land as a grid of dots, one SVG path.
//
// Source: Natural Earth 1:110m land polygons (public domain), which have coastlines and no
// borders at all, so the map takes no side on any boundary anywhere.
//
//   curl -sL https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson -o /tmp/land.geojson
//   node scripts/world-dots.mjs /tmp/land.geojson
//
// Every dot is a zero-length segment ("M x y h0") drawn with a round line cap, so the whole map
// is a single element no matter how many dots it has.

import { readFileSync, writeFileSync } from "node:fs";

const [, , source] = process.argv;
if (!source) throw new Error("usage: node scripts/world-dots.mjs <ne_110m_land.geojson>");

const STEP = 2.4; // degrees between dots
const NORTH = 80;
const SOUTH = -56; // Antarctica would be a long white smear across the bottom

const land = JSON.parse(readFileSync(source, "utf8"));
const rings = land.features.flatMap((feature) => {
  const { type, coordinates } = feature.geometry;
  return type === "Polygon" ? [coordinates] : coordinates;
});

/** Even-odd rule over a polygon's rings (outer and holes). */
function inside(lon, lat, polygon) {
  let hit = false;
  for (const ring of polygon) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const cols = Math.round(360 / STEP);
const rows = Math.round((NORTH - SOUTH) / STEP);
const dots = [];
for (let r = 0; r < rows; r++) {
  const lat = NORTH - (r + 0.5) * STEP;
  for (let c = 0; c < cols; c++) {
    const lon = -180 + (c + 0.5) * STEP;
    if (rings.some((polygon) => inside(lon, lat, polygon))) dots.push([c, r]);
  }
}

const path = dots.map(([c, r]) => `M${c} ${r}h0`).join("");
const out = `// Generated by scripts/world-dots.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// Land only, no borders. One unit is ${STEP} degrees; draw with a round line cap.

export const WORLD = { cols: ${cols}, rows: ${rows}, step: ${STEP}, north: ${NORTH} } as const;

export const WORLD_DOTS = "${path}";

/** Where a place falls on the grid, from its longitude and latitude. */
export function project(lon: number, lat: number): { x: number; y: number } {
  return { x: (lon + 180) / WORLD.step - 0.5, y: (WORLD.north - lat) / WORLD.step - 0.5 };
}
`;
writeFileSync(new URL("../lib/site/world-dots.ts", import.meta.url), out);
console.log(`${dots.length} dots, ${cols}x${rows}, ${path.length} bytes of path`);
